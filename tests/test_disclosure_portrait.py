"""Actual-file regression: set DISCLOSURE_SOURCE and DISCLOSURE_RESULT paths.

The result must have been generated by this release. Tests inspect the saved
PDF independently, including the numeric relationships in the difficult tables.
"""
import json, os, re, sys, unittest
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import fitz
import adaptive as a
import converter as c
import reviewed_disclosure as reviewed

SOURCE = os.environ.get('DISCLOSURE_SOURCE')
RESULT = os.environ.get('DISCLOSURE_RESULT')

@unittest.skipUnless(SOURCE and RESULT, 'Set paths to the supplied disclosure and converted result')
class DisclosurePortraitTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        assert reviewed.matches(Path(SOURCE)), 'Unexpected source fixture'
        cls.source = fitz.open(SOURCE)
        c.mark_source_page_numbers(cls.source)
        cls.result = fitz.open(RESULT)
        cls.report = json.loads(Path(RESULT + '.json').read_text())

    @classmethod
    def tearDownClass(cls):
        cls.source.close()
        cls.result.close()

    def outputs(self, source_page):
        record = self.report['pages'][source_page - 1]
        return [self.result[i] for i in range(record['output_start'] - 1, record['output_end'])]

    def test_every_page_portrait_every_text_span_mulish_11(self):
        self.assertEqual(self.report['engine_version'], a.VERSION)
        self.assertEqual(self.report['preserved_source_pages'], [])
        self.assertEqual(len(self.report['pages']), 192)
        fonts = set()
        for page in self.result:
            self.assertAlmostEqual(page.rect.width, 595.2756, places=2)
            self.assertAlmostEqual(page.rect.height, 841.8898, places=2)
            for block in page.get_text('dict')['blocks']:
                for line in block.get('lines', []):
                    for span in line['spans']:
                        fonts.add(span['font'])
                        self.assertIn('Mulish', span['font'], (page.number + 1, span))
                        self.assertAlmostEqual(span['size'], 11, places=2)
        self.assertTrue(any('Italic' in f for f in fonts))

    def test_source_text_styles_and_link_targets(self):
        for source_page, page in enumerate(self.source, 1):
            before = a.content_spans(page)[0]
            after = [s for p in self.outputs(source_page) for s in c.spans_of(p)]
            expected = a.inventory(''.join(s['text'] for s in before if s['text'] != '\uf0f1'))
            actual = a.inventory(''.join(s['text'] for s in after))
            self.assertFalse(expected - actual, (source_page, expected - actual))
            for name, predicate in (
                ('bold', c.is_bold),
                ('italic', lambda s: bool(s.get('flags', 0) & 2) or 'italic' in s['font'].lower() or 'oblique' in s['font'].lower()),
                ('underline', lambda s: s.get('underline', False)),
            ):
                expected = a.inventory(''.join(s['text'] for s in before if predicate(s)))
                actual = a.inventory(''.join(s['text'] for s in after if predicate(s)))
                self.assertFalse(expected - actual, (source_page, name, expected - actual))
            expected_urls = {s['uri'] for s in before if s.get('uri')}
            actual_urls = {link.get('uri') for p in self.outputs(source_page) for link in p.get_links()}
            self.assertFalse(expected_urls - actual_urls, source_page)

    def test_capital_table_quantity_and_cumulative_pairs(self):
        total = 0
        for number in range(103, 110):
            expected = []
            for y, row in c.rows_of(a.content_spans(self.source[number - 1])[0]):
                quantity = [s['text'] for s in row if 147 <= (s['bbox'][0] + s['bbox'][2])/2 < 224 and re.fullmatch(r'\**-?\d[\d,]*', s['text'])]
                capital = [s['text'] for s in row if (s['bbox'][0] + s['bbox'][2])/2 >= 498 and re.fullmatch(r'[\d,]+', s['text'])]
                if number == 106 and 550 < y < 560:
                    quantity = ['99,898,476']  # Visibly shifted source cell.
                if quantity and capital:
                    expected.append((quantity[0], ''.join(capital)))
            actual = []
            for page in self.outputs(number):
                for table in page.find_tables().tables:
                    for row in table.extract():
                        if len(row) != 7 or not row[1] or not row[6]:
                            continue
                        quantity = ''.join(row[1].split())
                        capital = ''.join(row[6].split()).strip('#')
                        if re.fullmatch(r'\**-?\d[\d,]*', quantity):
                            actual.append((quantity, capital))
            self.assertEqual(expected, actual, number)
            total += len(expected)
        self.assertEqual(total, 63)

    def test_borrowing_panels_every_cell_and_series(self):
        def clean(value):
            return ''.join((value or '').split()).replace('\xad', '')
        for number in (150, 151):
            original = self.source[number - 1].find_tables().tables[0].extract()
            if number == 150:
                original = original[1:]
            for columns in ((0, 1, 2, 3), (0, 4, 5, 6, 7)):
                expected = [[clean(row[i]) for i in columns] for row in original]
                actual = []
                for page in self.outputs(number):
                    for table in page.find_tables().tables:
                        if table.col_count == len(columns):
                            actual.extend([[clean(cell) for cell in row] for row in table.extract()[1:]])
                self.assertEqual(expected, actual, (number, columns))

if __name__ == '__main__':
    unittest.main()
